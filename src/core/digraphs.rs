/// The column-wrapped grid width Neovim's `:digraphs` listing uses
/// (`printdigraph`'s `list_width` in `digraph.c`) and the terminal width it
/// wraps against (`'columns'`'s default, matched here since `Engine` has no
/// notion of the active display width for a plain message string — #1302).
const DIGRAPH_LIST_WIDTH: usize = 13;
const DIGRAPH_LIST_COLUMNS: usize = 80;

/// How `:digraphs` renders one digraph's *result* character
/// (`printdigraph`'s `msg_outtrans` of the encoded char, `digraph.c`):
/// Vim never stores a real NUL in buffer/register text — a NL (`\n`,
/// `0x0A`) found there always *means* NUL, so it is always displayed as
/// NUL's own notation (`^@`), never as `^J`. C0 controls (`< 0x20` and
/// `DEL`) get Vim's caret notation; C1 controls (`0x80..=0x9F`) get its
/// `<xx>` hex notation; everything else (including the DEL-adjacent Latin-1
/// supplement and beyond) is printable and rendered as itself.
fn digraph_char_repr(result: char) -> String {
    let cp = result as u32;
    if cp == 0x0A {
        return "^@".to_string();
    }
    if cp < 0x20 {
        // SAFETY-free: `cp + 0x40` for `cp in 0x00..0x20` is `0x40..0x60`,
        // always a valid Latin-1 char (`@`..`_`).
        return format!("^{}", char::from_u32(cp + 0x40).unwrap());
    }
    if cp == 0x7F {
        return "^?".to_string();
    }
    if (0x80..=0x9F).contains(&cp) {
        return format!("<{cp:02x}>");
    }
    result.to_string()
}

/// Screen cells `result` occupies for the *trailing-pad decision* in
/// [`format_digraph_entry`] (`char2cells`/`ascii2cells`/`utf_char2cells` in
/// Neovim's `charset.c`/`mbyte.c`): 1 for printable ASCII, 2 for the `^X`
/// caret notation (`< 0x20` or `DEL` — Neovim's `dy_escape_width` default),
/// 4 for the `<xx>` hex notation (C1 controls), otherwise the real terminal
/// cell width (narrow/wide) via the same `quadraui::text_util` helper
/// `Engine::advance_one_cell` already uses for this classification (#1005)
/// — reused rather than re-derived per the Platform-Neutrality Rule in
/// `CLAUDE.md` — floored to 1: `utf_char2cells` never returns 0 (its
/// fallback is `return 1`), so a zero-width *composing* result (which
/// `quadraui::text_util::char_cell_width` correctly reports as 0 for
/// screen-layout purposes) still counts as 1 cell for *this* decision.
/// [`format_digraph_entry`] accounts for the composing case's *actual*
/// (zero) screen contribution separately.
fn digraph_char_cells(result: char) -> usize {
    let cp = result as u32;
    if cp < 0x80 {
        if (0x20..=0x7E).contains(&cp) {
            1
        } else {
            2
        }
    } else if (0x80..=0x9F).contains(&cp) {
        4
    } else {
        quadraui::text_util::char_cell_width(result).max(1) as usize
    }
}

/// Whether `result` is a Unicode *combining* mark needing a base character
/// to render onto (Neovim's `utf_iscomposing_first`, `mbyte.c`) — narrower
/// than "zero display width": a soft hyphen (`U+00AD`) is also zero-width
/// per `quadraui::text_util::char_cell_width` but is an ordinary spacing
/// character to Vim, not a composing mark (confirmed against the oracle:
/// `:digraphs`' `--` entry gets no extra leading space). Scoped to the
/// combining ranges [`BUILTIN_DIGRAPHS`] actually maps to — Arabic
/// harakat/tanwin (`U+064B..=U+0652`) and superscript alef (`U+0670`) — so
/// this needs revisiting if the table grows to cover another combining
/// block (`:h digraph-table`'s Hebrew/Thai/Devanagari points, none of
/// which Neovim's *default* table currently includes).
fn is_composing_mark(result: char) -> bool {
    matches!(result as u32, 0x064B..=0x0652 | 0x0670)
}

/// One digraph's rendered cell content (`printdigraph`, `digraph.c`):
/// `{c1}{c2} ` then, for a composing result (a combining mark with nothing
/// to combine onto), a leading space to draw it on, then the character
/// representation, then — only when [`digraph_char_cells`] is exactly 1 —
/// a padding space, then ` {result:>3}` (Vim's decimal codepoint,
/// right-justified to a minimum of 3 digits).
///
/// Returns the rendered text alongside its screen-cell width — needed
/// separately from `text.chars().count()` because a wide (CJK) result is
/// one `char` but two cells, and — the inverse case — a composing result's
/// prepended space is a real cell but the combining mark drawn onto it
/// contributes none (matching Neovim's own `msg_outtrans`, which tracks
/// `msg_col` by real screen width while [`digraph_char_cells`]'s
/// floored-to-1 value only ever drives the trailing-pad decision above);
/// the grid-wrapping column math in [`format_digraph_table`] needs the
/// former.
fn format_digraph_entry(c1: char, c2: char, result: char) -> (String, usize) {
    let mut s = String::new();
    let mut cells = 0usize;
    s.push(c1);
    s.push(c2);
    s.push(' ');
    cells += 3;
    let composing = is_composing_mark(result);
    if composing {
        s.push(' ');
        cells += 1;
    }
    s.push_str(&digraph_char_repr(result));
    let decision_cells = digraph_char_cells(result);
    if !composing {
        cells += decision_cells;
    }
    if decision_cells == 1 {
        s.push(' ');
        cells += 1;
    }
    let num = format!(" {:>3}", result as u32);
    cells += num.chars().count();
    s.push_str(&num);
    (s, cells)
}

/// Render `entries` as Neovim's `:digraphs` (no bang) does: a leading blank
/// line, then each entry column-wrapped into a `DIGRAPH_LIST_WIDTH`-wide
/// grid up to `DIGRAPH_LIST_COLUMNS` wide (`printdigraph`, `digraph.c`) —
/// wrap to a new line once the current column would leave less than one
/// full cell free, then pad forward to the next multiple of
/// `DIGRAPH_LIST_WIDTH` before printing the entry. `:digraphs!`'s
/// (bang) per-Unicode-block headers are out of scope (#1302 only covers the
/// bare `:digraphs` the oracle case uses), so `entries` is a flat sequence:
/// callers order it Neovim-native-table-then-custom to match
/// `listdigraphs`, which always lists the builtin table before user-defined
/// (`:digraph`) ones, never the other way around.
pub fn format_digraph_table(entries: impl Iterator<Item = (char, char, char)>) -> String {
    let mut out = String::from("\n");
    let mut col = 0usize;
    for (c1, c2, result) in entries {
        let (entry, entry_cells) = format_digraph_entry(c1, c2, result);
        if col > DIGRAPH_LIST_COLUMNS - DIGRAPH_LIST_WIDTH {
            out.push('\n');
            col = 0;
        }
        if !col.is_multiple_of(DIGRAPH_LIST_WIDTH) {
            let target = (col / DIGRAPH_LIST_WIDTH + 1) * DIGRAPH_LIST_WIDTH;
            out.push_str(&" ".repeat(target - col));
            col = target;
        }
        out.push_str(&entry);
        col += entry_cells;
    }
    out
}

/// Look up a digraph by the two characters typed, trying `(c1, c2)` and then
/// the reversed order. `extra` (from `Engine::custom_digraphs`, `:digraph`
/// user-defined entries) is consulted first so a user override wins.
pub fn lookup(
    c1: char,
    c2: char,
    extra: &std::collections::HashMap<(char, char), char>,
) -> Option<char> {
    if let Some(&ch) = extra.get(&(c1, c2)) {
        return Some(ch);
    }
    if let Some(&ch) = extra.get(&(c2, c1)) {
        return Some(ch);
    }
    for &(a, b, r) in BUILTIN_DIGRAPHS {
        if a == c1 && b == c2 {
            return Some(r);
        }
    }
    for &(a, b, r) in BUILTIN_DIGRAPHS {
        if a == c2 && b == c1 {
            return Some(r);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn looks_up_common_digraphs() {
        let empty = std::collections::HashMap::new();
        assert_eq!(lookup('a', ':', &empty), Some('ä'));
        assert_eq!(lookup('-', '>', &empty), Some('→'));
        assert_eq!(lookup('s', 's', &empty), Some('ß'));
    }

    #[test]
    fn falls_back_to_reversed_order() {
        let empty = std::collections::HashMap::new();
        // ":a" isn't a table entry directly, but "a:" is.
        assert_eq!(lookup(':', 'a', &empty), Some('ä'));
    }

    #[test]
    fn custom_digraph_overrides_and_is_checked_first() {
        let mut extra = std::collections::HashMap::new();
        extra.insert(('z', 'z'), '★');
        assert_eq!(lookup('z', 'z', &extra), Some('★'));
        // A custom entry for a pair that also exists built-in wins.
        extra.insert(('a', ':'), '#');
        assert_eq!(lookup('a', ':', &extra), Some('#'));
    }

    #[test]
    fn unknown_pair_returns_none() {
        let empty = std::collections::HashMap::new();
        assert_eq!(lookup('q', 'q', &empty), None);
    }

    #[test]
    fn no_duplicate_keys_in_builtin_table() {
        let mut seen = std::collections::HashSet::new();
        for &(a, b, _) in BUILTIN_DIGRAPHS {
            assert!(seen.insert((a, b)), "duplicate digraph key {a}{b}");
        }
    }

    // #1302: `format_digraph_table` reimplements Neovim's `printdigraph`
    // grid layout; these pin the exact rendered bytes for representative
    // slices of `BUILTIN_DIGRAPHS`, each confirmed against a live
    // `nvim --headless -u NONE -i NONE` oracle (`:digraphs`, no bang) —
    // see `tests/nvim_conformance.rs`'s `msg:ex::digraphs lists the digraph
    // table` case, which now passes against the same oracle end-to-end.
    // Without this fix (Vim's table/one-per-line layout reinstated), every
    // assertion below fails — this is real regression coverage, not a
    // vacuous "some string came back" check.

    #[test]
    fn table_render_starts_with_leading_blank_line_and_control_char_row() {
        let out = format_digraph_table(BUILTIN_DIGRAPHS.iter().copied());
        // Neovim's `listdigraphs` puts a blank line first (`msg_putchar('\n')`
        // before the loop), then six 13-cell columns per row. `NU` (mnemonic
        // for NUL) is vimcode's/Neovim's first table entry, and Vim never
        // stores a real NUL in text — it always displays as `^@`, even
        // though the digraph's stored codepoint is 10 (LF), not 0.
        let expected_first_two_lines = "\n\
NU ^@  10    SH ^A   1    SX ^B   2    EX ^C   3    ET ^D   4    EQ ^E   5\n\
AK ^F   6    BL ^G   7    BS ^H   8    HT ^I   9    LF ^@  10    VT ^K  11";
        assert!(
            out.starts_with(expected_first_two_lines),
            "unexpected table head: {:?}",
            &out[..out.len().min(200)]
        );
    }

    #[test]
    fn table_render_matches_oracle_for_c1_control_hex_notation() {
        // C1 controls (`0x80..=0x9F`) render as `<xx>` hex notation, 4
        // cells wide, distinct from the `^X` caret notation C0 controls use.
        let out = format_digraph_table(BUILTIN_DIGRAPHS.iter().copied());
        assert!(out.contains("PA <80> 128  HO <81> 129"));
    }

    #[test]
    fn table_render_matches_oracle_for_composing_arabic_diacritics() {
        // Arabic harakat (U+064B..=U+0652) are composing marks: Neovim
        // prepends a space to draw them on, and — since a combining mark's
        // *real* screen width is 0 even though the padding-decision width
        // is floored to 1 — the grid column math after one lands 1 cell
        // later than a naive char-count would predict. This is the subtlest
        // part of the layout fix (#1302); without it, this exact row
        // doesn't match.
        let out = format_digraph_table(BUILTIN_DIGRAPHS.iter().copied());
        assert!(out.contains(
            "w+ و  1608   j+ ى  1609   y+ ي  1610   :+  ً  1611   \"+  ٌ  1612   =+  ٍ  1613"
        ));
    }

    #[test]
    fn table_render_matches_oracle_for_wide_cjk_glyph() {
        // A wide (CJK, 2-cell) result glyph is one `char` but two screen
        // cells — the grid math must track cells, not `chars().count()`.
        let out = format_digraph_table(BUILTIN_DIGRAPHS.iter().copied());
        assert!(out.contains("IS 　 12288  ,_ 、 12289"));
    }

    #[test]
    fn ex_digraphs_lists_builtin_before_custom() {
        // Neovim's `listdigraphs` always lists the builtin `digraphdefault`
        // table before any `:digraph`-defined custom entries, never the
        // other way (`digraph.c`) — `ex_digraphs` used to list custom
        // entries first.
        let custom = [('z', 'z', '★')];
        let out = format_digraph_table(BUILTIN_DIGRAPHS.iter().copied().chain(custom));
        let nu_pos = out.find("NU ^@").expect("builtin entry present");
        let zz_pos = out.find("zz ★").expect("custom entry present");
        assert!(
            nu_pos < zz_pos,
            "builtin table must precede custom entries in the listing"
        );
    }
}
